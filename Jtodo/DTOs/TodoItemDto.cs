using Jtodo.Values;
using Jtodo.ViewModels;
using System;
using System.ComponentModel;

namespace Jtodo.DTOs
{
    public class TodoItemDto : ViewModelBase, IDataErrorInfo
    {
        private ulong _id;
        private string _title;
        private string _description;
        private DateTime _startDate;
        private DateTime _dueDate;
        private Priority _priority;
        private Status _status;
        private ulong _typeId;
        private bool _isEditing;
        private string _typeName = string.Empty;
        private string _typeColor = "#9E9E9E"; // Default gray color

        public ulong Id
        {
            get => _id;
            set { _id = value; OnPropertyChanged(nameof(Id)); }
        }

        public string Title
        {
            get => _title;
            set { _title = value; OnPropertyChanged(nameof(Title)); }
        }

        public string Description
        {
            get => _description;
            set { _description = value; OnPropertyChanged(nameof(Description)); }
        }

        public DateTime StartDate
        {
            get => _startDate;
            set { _startDate = value; OnPropertyChanged(nameof(StartDate)); OnPropertyChanged(nameof(DueDate)); }
        }

        public DateTime DueDate
        {
            get => _dueDate;
            set { _dueDate = value; OnPropertyChanged(nameof(DueDate)); OnPropertyChanged(nameof(StartDate)); }
        }

        public Priority Priority
        {
            get => _priority;
            set 
            { 
                _priority = value; 
                OnPropertyChanged(nameof(Priority));
                OnPropertyChanged(nameof(PriorityColor));
            }
        }

        public Status Status
        {
            get => _status;
            set 
            { 
                _status = value; 
                OnPropertyChanged(nameof(Status));
                OnPropertyChanged(nameof(StatusColor));
            }
        }

        public ulong TypeId
        {
            get => _typeId;
            set { _typeId = value; OnPropertyChanged(nameof(TypeId)); }
        }

        public bool IsEditing
        {
            get => _isEditing;
            set { _isEditing = value; OnPropertyChanged(nameof(IsEditing)); }
        }

        // For display purposes - will be populated by ViewModel
        public string TypeName
        {
            get => _typeName;
            set { _typeName = value; OnPropertyChanged(nameof(TypeName)); }
        }

        // Type color - will be populated by ViewModel from database
        public string TypeColor
        {
            get => _typeColor;
            set { _typeColor = value; OnPropertyChanged(nameof(TypeColor)); }
        }

        // Color properties for UI badges
        public string StatusColor
        {
            get
            {
                return Status switch
                {
                    Status.Pending => "#9E9E9E",      // Gray
                    Status.Progress => "#2196F3",   // Blue
                    Status.Completed => "#4CAF50",    // Green
                    Status.Expired => "#FF9800",     // Orange
                    Status.Cancelled => "#F44336",    // Red
                    _ => "#9E9E9E"
                };
            }
        }

        public string PriorityColor
        {
            get
            {
                return Priority switch
                {
                    Priority.Low => "#4CAF50",        // Green
                    Priority.Medium => "#FF9800",     // Orange
                    Priority.High => "#F44336",       // Red
                    Priority.Critical => "#9C27B0",   // Purple
                    _ => "#9E9E9E"
                };
            }
        }

        public TodoItemDto()
        {
            _title = string.Empty;
            _description = string.Empty;
            _startDate = DateTime.Now;
            _dueDate = DateTime.Now.AddDays(7);
            _priority = Priority.Low;
            _status = Status.Pending;
        }

        public TodoItemDto(string title, string description, ulong typeId)
        {
            _id = 0;  // Auto-generated by database
            _title = title;
            _description = description;
            _startDate = DateTime.Now;
            _dueDate = DateTime.Now.AddDays(7);
            _priority = Priority.Low;
            _status = Status.Pending;
            _typeId = typeId;
        }

        public TodoItemDto(string title, string description, 
            DateTime startDate, DateTime dueDate, 
            Priority priority, Status status, ulong typeId)
        {
            _id = 0; // Auto-generated by database
            _title = title;
            _description = description;
            _startDate = startDate;
            _dueDate = dueDate;
            _priority = priority;
            _status = status;
            _typeId = typeId;
        }

        public TodoItemDto(ulong id,string title, string description,
            DateTime startDate, DateTime dueDate,
            Priority priority, Status status, ulong typeId)
        {
            _id = id;
            _title = title;
            _description = description;
            _startDate = startDate;
            _dueDate = dueDate;
            _priority = priority;
            _status = status;
            _typeId = typeId;
        }

        // IDataErrorInfo implementation
        public string Error => string.Empty;

        public string this[string columnName]
        {
            get
            {
                string error = string.Empty;

                switch (columnName)
                {
                    case nameof(Title):
                        if (string.IsNullOrWhiteSpace(Title))
                            error = "Title cannot be empty";
                        break;

                    case nameof(DueDate):
                        if (DueDate < StartDate)
                            error = "Due date cannot be before start date";
                        break;

                    case nameof(StartDate):
                        if (StartDate > DueDate)
                            error = "Start date cannot be after due date";
                        break;
                }

                return error;
            }
        }
    }
}
